def source_key(name: str) -> str:
    """The registry key of a `_meta.source` value or catalog item name; refuses one the registry doesn't know."""
    if name in _NAMES:
        return _NAMES[name]
    if key := next((k for prefix, k in _PREFIXES.items() if name.startswith(prefix)), None):
        return key
    raise KeyError(f"no licence recorded for source {name!r}: add it to den/licences.py")


def kind(keys: Iterable[str]) -> Kind:
    """The most restrictive class among `keys`."""
    return max((BY_KEY[k].kind for k in keys), key=RANK.__getitem__, default="open")


def allowed(k: Kind, public: bool) -> bool:
    """May a file of class `k` be uploaded: never if restricted, privately if unspecified, else always."""
    return RANK[k] < RANK["restricted" if not public else "unspecified"]


