"""Whose data is in `data/`, under what terms, and whether it may leave this machine.

Every record names its source (`_meta.source`; a buried probe, its `parent_source`), every raw file sits under a
pinned catalog item, so each file in `data/` resolves to the sources it contains. Each source's licence was checked
at its primary source (the pinned dataset card, the licence file shipped in the archive, or the publisher's terms);
`evidence` says where. A file takes the most restrictive class among its sources:

- `open`: permissive (MIT, Apache-2.0, BSD, CC0, CC-BY, public domain, "free use");
- `share-alike`: CC-BY-SA; derived data must keep the licence;
- `non-commercial`: CC-BY-NC or research-only terms; redistribution allowed for non-commercial use, marked as such;
- `unspecified`: no licence stated; kept to a private copy, never published;
- `restricted`: the terms forbid redistribution; never uploaded anywhere.

`den licences` writes the notices into `data/` (`LICENSES.md`, `LICENSES/`, `README.md` as the Hub dataset card, and a
`SOURCE-LICENSE.md` beside every dataset, saying what each file there holds and under what terms); `scripts/mirror.py` uploads only what `allowed` permits. Not legal advice:
the classes are conservative readings of each source's own terms.
"""

